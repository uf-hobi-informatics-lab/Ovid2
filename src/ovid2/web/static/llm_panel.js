  function parseSse(buffer, onEvent) {
    var idx;
    while ((idx = buffer.indexOf("\n\n")) !== -1) {
      var frame = buffer.slice(0, idx);
      buffer = buffer.slice(idx + 2);
      var data = [];
      frame.split("\n").forEach(function (l) {
        if (l.indexOf("data:") === 0) data.push(l.slice(5).replace(/^ /, ""));
      });
      if (!data.length) continue;
      try { onEvent(JSON.parse(data.join("\n"))); } catch (e) { /* skip */ }
    }
    return buffer;
  }

  function runProposal(m, p, formReq) {
    if (state.busy || (p.state && p.state !== "pending")) return;
    var fl = formLib();
    var editable = !!(formReq && fl && fl.editable(p));
    // A form proposal sends what the human completed; the stored body is the
    // redacted copy (secret values never persist or reach the model).
    var reqPath = editable ? formReq.path : p.path;
    var reqBody = editable ? formReq.body : p.body;
    if (editable) { p.path = formReq.path; p.body = fl.redactedBody(p); }
    if (!/^\/api\/v1\/[A-Za-z0-9_\-%.:\/]+$/.test(reqPath || "") ||
        ["POST", "PUT"].indexOf(p.method) === -1) {
      p.state = "failed";
      p.outcome = "Refused: not an Ovid2 API action.";
      save(); renderAll();
      return;
    }
    p.state = "running";
    renderAll();
    var opts = { method: p.method, headers: { "Accept": "application/json" }, credentials: "same-origin" };
    if (p.method !== "GET") {
      opts.headers["Content-Type"] = "application/json";
      opts.body = JSON.stringify(reqBody || {});
    }
    fetch(reqPath, opts).then(function (resp) {
      return resp.text().then(function (txt) {
        var data;
        try { data = JSON.parse(txt); } catch (e) { data = txt; }
        return { status: resp.status, ok: resp.ok, data: data };
      });
    }).then(function (r) {
      var detail = r.data && r.data.detail;
      if (r.status === 202 && detail && detail.status === "awaiting_approval") {
        p.state = "awaiting";
        p.outcome = "Awaiting human approval (" + detail.approval_id + ").";
      } else {
        p.state = r.ok ? "done" : "failed";
        p.outcome = "HTTP " + r.status;
      }
      save();
      renderAll();
      var shown = typeof r.data === "string" ? r.data : JSON.stringify(r.data);
      if (shown.length > 4000) shown = shown.slice(0, 4000) + "…";
      if (!r.ok) {
        var d = r.data && r.data.detail;
        if (d) p.outcome += ": " + (typeof d === "string" ? d : JSON.stringify(d)).slice(0, 300);
        if (editable) { p.state = "pending"; save(); renderAll(); return; } // let the human fix the form
      }
      var report = "[I ran the proposed action `" + p.name + "` (" + p.method + " " + p.path +
           (editable ? ", body " + JSON.stringify(p.body) : "") +
           ") → HTTP " + r.status + "]\n```json\n" + shown + "\n```";
      if (!editable) {
        send(report + "\nBriefly confirm the outcome and suggest a next step.", { kind: "action" });
        return;
      }
      p.report = report;
      save();
      proposalsSettled(m);
    }).catch(function (err) {
      p.state = editable ? "pending" : "failed";
      p.outcome = (err && err.message) || "Network error";
      save();
      renderAll();
    });
  }

  function uiBody(newMessages) {
    var body = { messages: newMessages };
    if (state.sessionId) body.session_id = state.sessionId;
    var ctx = null;
    try { ctx = uiContext(); } catch (e) { ctx = null; }
    if (ctx) body.ui_context = ctx;
    return body;
  }

  function send(text, opts) {
    if (state.busy || !text.trim()) return;
    var userMsg = { role: "user", content: text };
    if (opts && opts.kind) userMsg.meta = { kind: opts.kind };
    state.messages.push(userMsg);
    var reply = { role: "assistant", content: "",
                  meta: { notices: [], reasoning: "", tools: [], proposals: [], uiActions: [] } };
    state.messages.push(reply);
    renderAll();
    save();

    var canvas = $("llm-canvas");
    var node = canvas && canvas.lastChild;
    var pending = false;
    function repaint() {
      if (pending) return;
      pending = true;
      window.requestAnimationFrame(function () {
        pending = false;
        if (!canvas) return;
        var fresh = renderMessage(reply);
        if (state.busy) fresh.querySelector(".llm-body").classList.add("llm-cursor");
        if (node && node.parentNode === canvas) canvas.replaceChild(fresh, node);
        else canvas.appendChild(fresh);
        node = fresh;
        canvas.scrollTop = canvas.scrollHeight;
      });
    }

    // Only the new message travels; the server prepends the saved history.
    var outgoing = [{ role: "user", content: text.slice(0, 32000) }];
    if (opts && opts.kind) outgoing[0].kind = opts.kind;
    if (!state.session) {
      state.session = { title: "", title_source: "pending", last_prompt_tokens: 0,
                        total_prompt_tokens: 0, total_completion_tokens: 0 };
    }
    renderSessionChrome();

    state.controller = new AbortController();
    setBusy(true);
    repaint();

    function onEvent(ev) {
      var m = reply.meta;
      switch (ev.type) {
        case "meta": m.route = ev.route; m.model = ev.model; m.connection = ev.connection; break;
        case "notice": m.notices.push(ev.message); break;
        case "decision": m.decision = ev; break;
        case "reasoning": m.reasoning += ev.text || ""; break;
        case "delta": reply.content += ev.text || ""; break;
        case "usage": m.completion_tokens = ev.completion_tokens; m.prompt_tokens = ev.prompt_tokens; break;
        case "error": m.error = ev.message || ev.code; break;
        case "tool_call":
          m.tools.push({ id: ev.id, name: ev.name, method: ev.method, path: ev.path, arguments: ev.arguments });
          break;
        case "tool_result":
          var hit = null;
          m.tools.forEach(function (t) { if (t.id === ev.id) hit = t; });
          if (!hit) { hit = { id: ev.id, name: ev.name }; m.tools.push(hit); }
          hit.result = { status: ev.status, ok: ev.ok, elapsed_ms: ev.elapsed_ms,
                         summary: ev.summary, preview: (ev.preview || "").slice(0, 4000),
                         rejected: !!ev.rejected, duplicate: !!ev.duplicate };
          break;
        case "proposal":
          m.proposals.push({ id: ev.id, name: ev.name, method: ev.method, path: ev.path,
                             body: ev.body, state: "pending" });
          break;
        case "open_draft":
          var dp = { id: ev.id, name: ev.name, method: ev.method, path: ev.path,
                     body: ev.body, state: "running", draft: true };
          m.proposals.push(dp);
          state.pendingDrafts.push(dp);
          break;
        case "ui_action":
          // Applied once, live, as the event arrives — never on replay.
          var ua = { id: ev.id, name: ev.name, args: ev.args || {}, state: "pending" };
          applyUiAction(ua);
          m.uiActions.push(ua);
          save();
          break;
        case "done": m.elapsed_ms = ev.elapsed_ms; if (!m.route || m.route === "none") m.route = ev.route; break;
        case "session_open":
          rememberSession(ev.session_id);
          break;
        case "session":
          rememberSession(ev.session_id);
          reply.seq = ev.assistant_seq;
          userMsg.seq = ev.assistant_seq - 1;
          if (ev.context_window) state.contextWindow = ev.context_window;
          state.session = Object.assign(state.session || {}, {
            session_id: ev.session_id, title: ev.title, title_source: ev.title_source,
            last_prompt_tokens: ev.last_prompt_tokens, total_prompt_tokens: ev.total_prompt_tokens,
            total_completion_tokens: ev.total_completion_tokens
          });
          renderSessionChrome();
          if (ev.title_source === "pending") pollTitle(ev.session_id, 0);
          if (isHistoryOpen()) refreshHistory();
          return;
      }
      repaint();
    }

    fetch("/api/v1/llm/chat/stream", {
      method: "POST",
      headers: { "Content-Type": "application/json", "Accept": "text/event-stream" },
      body: JSON.stringify(uiBody(outgoing)),
      signal: state.controller.signal
    }).then(function (resp) {
      if (!resp.ok) {
        return resp.json().catch(function () { return {}; }).then(function (b) {
          var d = b && b.detail;
          if (resp.status === 404 && d === "Session not found.") rememberSession(null);
          onEvent({ type: "error", message: (typeof d === "string" ? d : JSON.stringify(d || {})) || ("HTTP " + resp.status) });
        });
      }
      var reader = resp.body.getReader();
      var decoder = new TextDecoder();
      var buffer = "";
      function pump() {
        return reader.read().then(function (r) {
          if (r.done) { parseSse(buffer + "\n\n", onEvent); return; }
          buffer = parseSse(buffer + decoder.decode(r.value, { stream: true }), onEvent);
          return pump();
        });
      }
      return pump();
    }).catch(function (err) {
      if (err && err.name === "AbortError") reply.meta.notices.push("Stopped.");
      else onEvent({ type: "error", message: (err && err.message) || "Network error" });
    }).then(function () {
      state.controller = null;
      setBusy(false);
      renderSessionChrome();
      if (!reply.content && !reply.meta.error && !reply.meta.decision &&
          !reply.meta.proposals.length && !reply.meta.uiActions.length) {
        reply.content = "_(no answer)_";
      }
      save();
      repaint();
      var drafts = state.pendingDrafts.splice(0);
      if (drafts.length && pendingForms(reply).length) {
        // The draft needs what the forms create (account / address): hold it
        // until they are run, then proposalsSettled() opens it.
        drafts.forEach(function (d) { d.state = "held"; });
        state.pendingNav = null;
        save(); renderAll();
        return;
      }
      if (drafts.length) { state.pendingNav = null; openDraft(drafts[0]); return; }
      var nav = state.pendingNav;
      state.pendingNav = null;
      if (nav === WF_PREFILL_URL) { window.location.assign(nav); return; }
      var input = $("llm-input");
      if (input) input.focus();
    });
  }

  /* Create a draft job (opens_draft tool) with the user's own session and
     open its run page. A draft is never executed by the worker — the human
     presses the (breathing) ▶ on the run page to launch it. */
  function openDraft(p) {
    if (!/^\/api\/v1\/(job-drafts|report-drafts|workflow-drafts|pipelines\/[A-Za-z0-9_\-%.]+\/draft)$/.test(p.path || "") ||
        p.method !== "POST") {
      p.state = "failed";
      p.outcome = "Refused: not a draft-job route.";
      save(); renderAll();
      return;
    }
    fetch(p.path, {
      method: "POST", credentials: "same-origin",
      headers: { "Accept": "application/json", "Content-Type": "application/json" },
      body: JSON.stringify(p.body || {})
    }).then(function (resp) {
      return resp.text().then(function (txt) {
        var data;
        try { data = JSON.parse(txt); } catch (e) { data = txt; }
        return { status: resp.status, ok: resp.ok, data: data };
      });
    }).then(function (r) {
      if (r.ok && r.data && r.data.report_id && p.path === "/api/v1/report-drafts") {
        var rurl = "/reports/" + encodeURIComponent(r.data.report_id);
        p.state = "done";
        p.url = rurl;
        p.outcome = "Draft report created — review it in the Report Studio and press Save to keep it.";
        save(); renderAll();
        window.location.assign(rurl);
        return;
      }
      if (r.ok && r.data && r.data.name && p.path === "/api/v1/workflow-drafts") {
        var wurl = "/workflows/" + encodeURIComponent(r.data.name) + "?draft=1";
        p.state = "done";
        p.url = wurl;
        p.outcome = "Draft workflow saved (disabled) — review it on the canvas, then Save and enable or Run it.";
        save(); renderAll();
        window.location.assign(wurl);
        return;
      }
      if (r.ok && r.data && r.data.instance_id) {
        var url = "/runs/" + encodeURIComponent(r.data.instance_id);
        p.state = "done";
        p.url = url;
        p.outcome = "Draft created — launch it with ▶ on the run page; its live status is shown there.";
        save(); renderAll();
        window.location.assign(url);
        return;
      }
      var d = r.data && r.data.detail;
      p.state = "failed";
      p.outcome = "HTTP " + r.status + (d ? ": " + (typeof d === "string" ? d : JSON.stringify(d)) : "");
      save(); renderAll();
      send("[Creating the draft `" + p.name + "` failed → " + p.outcome + "]\n" +
           "Fix the arguments using read tools and draft it again.", { kind: "action" });
    }).catch(function (err) {
      p.state = "failed";
      p.outcome = (err && err.message) || "Network error";
      save(); renderAll();
    });
  }

