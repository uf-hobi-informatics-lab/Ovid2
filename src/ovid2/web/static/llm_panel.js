  // Apply a ui_action event. ``u`` is the record stored on the message.
  function applyUiAction(u) {
    var err = checkUiArgs(u.name, u.args);
    if (err) { u.state = "refused"; u.outcome = "Refused: " + err + "."; return; }
    if (u.name === "edit_report_layout") { applyReportEdit(u); return; }
    if (u.name === "open_workflow_canvas") { applyCanvasPrefill(u); return; }
    var t = themeLib(), a = appLib(), args = u.args;
    var before = snapshot(u.name === "save_appearance");
    try {
      if (u.name === "save_appearance") {
        var arr = a.readSaved().filter(function (e) { return e && e.name !== args.name; });
        arr.push({ name: args.name, theme: t.currentTheme(), overrides: foldedOverrides() });
        a.writeSaved(arr);
      } else if (u.name === "apply_saved_appearance") {
        var entry = a.readSaved().filter(function (e) { return e && e.name === args.name; })[0];
        var ov = {};
        Object.keys((entry && entry.overrides) || {}).forEach(function (k) {
          if (!checkVar(k, entry.overrides[k])) ov[k] = entry.overrides[k];
        });
        t.writeCustom({});
        a.writeAppearance(ov);
        if (entry && t.isKnownSlug(entry.theme)) t.applyTheme(entry.theme);
      } else {
        if (args.theme || args.reset) { t.writeCustom({}); a.writeAppearance({}); }
        if (args.theme) t.applyTheme(args.theme);
        if (args.colors) {
          var c = t.readCustom();
          Object.keys(args.colors).forEach(function (k) { c[k] = args.colors[k].toLowerCase(); });
          t.writeCustom(c);
        }
        if (args.appearance) {
          var map = a.readAppearance();
          Object.keys(args.appearance).forEach(function (k) { map[k] = args.appearance[k]; });
          if (args.appearance["--bg"] && !args.appearance["--bg-elev"]) delete map["--bg-elev"];
          a.writeAppearance(map);
        }
      }
      a.repaint();
      // Legibility guard: never leave the page (and this Undo button)
      // unreadable. Skipped when a token is not a plain hex value.
      var fg = computedHex("--fg"), bg = computedHex("--bg");
      if (fg && bg && t.contrastRatio && t.contrastRatio(fg, bg) < MIN_CONTRAST) {
        restore(before);
        u.state = "refused";
        u.outcome = "Refused: text colour " + fg + " on " + bg + " would be unreadable (contrast " +
          t.contrastRatio(fg, bg).toFixed(1) + ":1, need " + MIN_CONTRAST + ":1).";
        return;
      }
      if (a.refresh) a.refresh();
      u.before = before;
      u.state = "applied";
      u.outcome = describeUi(u.name, args) + ".";
    } catch (e) {
      restore(before);
      u.state = "refused";
      u.outcome = "Failed: " + ((e && e.message) || "error") + ".";
    }
  }

  // The Studio validates the ops against the chart library + source on the
  // server (POST /reports/{id}/ops save=false) before touching its working
  // copy; nothing is saved until the human presses Save.
  function applyReportEdit(u) {
    var st = studioLib();
    u.state = "pending";
    u.outcome = "Applying report edits…";
    st.applyOps(u.args.ops).then(function (notes) {
      u.state = "applied";
      u.before = { report_id: st.info().report_id };
      u.outcome = "Report: " + ((u.args.note || (notes || []).join("; ")) || "updated") + " (unsaved — press Save in the Studio).";
    }, function (e) {
      u.state = "refused";
      u.outcome = "Refused: " + ((e && e.message) || "invalid edit") +
        ((e && e.errors && e.errors.length) ? " — " + e.errors.slice(0, 3).join("; ") : "") + ".";
    }).then(function () { save(); renderAll(); });
  }

  // Hand the working copy to the canvas page; navigation waits for the end
  // of the stream (like a draft) so the assistant's explanation still lands.
  function applyCanvasPrefill(u) {
    try {
      sessionStorage.setItem(WF_PREFILL_KEY, JSON.stringify(u.args));
    } catch (e) {
      u.state = "refused";
      u.outcome = "Refused: this browser blocks session storage.";
      return;
    }
    u.before = { url: window.location.pathname + window.location.search };
    u.state = "applied";
    u.outcome = describeUi(u.name, u.args) + " — opening it now; bind what is missing and press Save.";
    state.pendingNav = WF_PREFILL_URL;
  }

  function undoUiAction(u) {
    if (u.state !== "applied" || !u.before) return;
    if (u.name === "open_workflow_canvas") {
      try { sessionStorage.removeItem(WF_PREFILL_KEY); } catch (e) { /* ignore */ }
      if (state.pendingNav === WF_PREFILL_URL) state.pendingNav = null;
      u.state = "undone";
      u.outcome = describeUi(u.name, u.args) + " — undone.";
      save(); renderAll();
      var back = u.before.url || "/workflows";
      if (back.charAt(0) !== "/" || back.charAt(1) === "/") back = "/workflows";
      if (window.location.pathname + window.location.search !== back) window.location.assign(back);
      return;
    }
    if (u.name === "edit_report_layout") {
      var st = studioLib(), info = st && st.info ? st.info() : null;
      if (!info || info.report_id !== u.before.report_id) {
        u.outcome = "Open that report in the Studio to undo (use its Undo button).";
        save(); renderAll();
        return;
      }
      st.undo();
      u.state = "undone";
      u.outcome = (u.outcome || "Report edit") + " — undone.";
      save(); renderAll();
      return;
    }
    restore(u.before);
    u.state = "undone";
    u.outcome = describeUi(u.name, u.args) + " \u2014 undone.";
    save();
    renderAll();
  }

