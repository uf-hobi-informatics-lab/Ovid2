def _gen_run_kinds() -> str:
    from ovid2.run_kinds import KIND_ALIASES, KIND_REGISTRY

    rows = []
    for spec in KIND_REGISTRY.values():
        rows.append(
            [
                f"`{spec.name}`",
                spec.label,
                spec.description,
                f"`ovid2 {spec.cli_subcommand}`",
                "yes" if spec.package_required else "no",
                "yes" if spec.uses_cdm else "no",
                "job only" if spec.job_only else "pipeline",
            ]
        )
    aliases = ", ".join(f"`{a}` → `{t}`" for a, t in sorted(KIND_ALIASES.items()))
    return "\n".join(
        [
            _front(
                "Run kinds",
                "The job types Ovid2 can execute and what each one does.",
                ["user", "developer"],
            ),
            "A pipeline config's *kind* decides which executor command runs, whether a "
            "pipeline package and a CDM are required, and which form fields the Submit "
            "page shows. Narrative guide: [Running jobs](../04-running-jobs/index.md).\n",
            _table(
                ["Kind", "Label", "Description", "Executor", "Package", "CDM", "Created as"],
                rows,
            ),
            f"Deprecated aliases accepted on input: {aliases}.\n" if aliases else "",
        ]
    )


def _gen_transforms() -> str:
    from ovid2.config.transforms_catalogue import CATEGORIES, TRANSFORM_CATALOGUE

    lines = [
        _front(
            "Transforms catalogue",
            "Every op in the public transformations library, by category, with its parameters.",
            ["developer", "researcher"],
        ),
        "Transforms are CDM-agnostic, lazy DataFrame ops you compose into chains (from a "
        "mapper via `apply_transforms`, or over HTTP / MCP). Guide: "
        "[Transforms library](../06-authoring/transforms.md). Ops marked *spark* need a "
        "Spark-family engine.\n",
    ]
    for cat in CATEGORIES:
        entries = sorted(
            (t for t in TRANSFORM_CATALOGUE if t["category"] == cat), key=lambda t: t["name"]
        )
        lines.append(f"## {cat.capitalize()}\n")
        rows = []
        for t in entries:
            schema = t.get("params_schema") or {}
            req = set(schema.get("required") or [])
            params = ", ".join(
                f"`{p}`" + ("*" if p in req else "") for p in (schema.get("properties") or {})
            )
            rows.append([f"`{t['name']}`", t["summary"], params, t.get("requires_family") or "any"])
        lines.append(_table(["Op", "Summary", "Params (* = required)", "Engine"], rows))
    return "\n".join(lines)


def _registry_rows(
    registry: dict[str, Any], extra: Callable[[str, Any], list[Any]] | None = None
) -> list[list[Any]]:
    rows = []
    for name in sorted(registry):
        cls = registry[name]
        row = [f"`{name}`", _first_para(cls.__doc__)]
        if extra is not None:
            row.extend(extra(name, cls))
        rows.append(row)
    return rows


_PARAM_LINE_RE = re.compile(r"^    ([a-z_]+):\s*(.*)$")


def _docstring_params(doc: str | None) -> list[tuple[str, str]]:
    """Parse a ``Params:`` block (``name: description`` lines) from a docstring."""
    if not doc:
        return []
    lines = inspect.cleandoc(doc).splitlines()
    try:
        start = next(i for i, ln in enumerate(lines) if ln.strip() == "Params:")
    except StopIteration:
        return []
    params: list[tuple[str, str]] = []
    for line in lines[start + 1 :]:
        if line and not line.startswith(" "):
            break
        match = _PARAM_LINE_RE.match(line)
        if match:
            params.append((match.group(1), match.group(2)))
        elif params and line.strip():
            name, text = params[-1]
            params[-1] = (name, f"{text} {line.strip()}")
    return [(n, _clean_rst(" ".join(t.split()))) for n, t in params]


def _gen_mapper_ops() -> str:
    from ovid2.mappers.registry import MAP_OPS

    lines = [
        _front(
            "Mapper ops",
            "Every declarative op a mapper spec can use, with its parameters.",
            ["developer"],
        ),
        "Mapper specs list ops by name; each op transforms one or more columns. "
        "Authoring guide: [Mapper specs](../06-authoring/mappers.md).\n",
        _table(["Op", "What it does"], _registry_rows(MAP_OPS)),
    ]
    for name in sorted(MAP_OPS):
        module = importlib.import_module(MAP_OPS[name].__module__)
        params = _docstring_params(module.__doc__)
        lines.append(f"## {name}\n")
        lines.append(_first_para(MAP_OPS[name].__doc__) + "\n")
        if params:
            lines.append(_table(["Param", "Meaning"], ([f"`{n}`", t] for n, t in params)))
    return "\n".join(lines)


