def _gen_fixers() -> str:
    from ovid2.transformations.fixers.common.registry import COMMON_FIXES, FIXER_SCOPES

    lines = [
        _front(
            "Fixer catalogue",
            "Every reusable common fixer, grouped by scope.",
            ["developer", "researcher"],
        ),
        "Fixers are data-correction steps chained per table in a pipeline's "
        "`fixer_configs.py`. A *generic* fixer works on any CDM; a CDM-scoped fixer only "
        "on that CDM. Guide: [Fixer chains](../06-authoring/fixers.md).\n",
    ]
    scopes: dict[str, list[str]] = {}
    for name, scope in FIXER_SCOPES.items():
        scopes.setdefault(scope, []).append(name)
    for scope in sorted(scopes, key=lambda s: (s != "generic", s)):
        lines.append(f"## {scope}\n")
        lines.append(
            _table(
                ["Fixer", "What it does"],
                _registry_rows({n: COMMON_FIXES[n] for n in scopes[scope] if n in COMMON_FIXES}),
            )
        )
    return "\n".join(lines)


def _resolve_doc(target: Any) -> str:
    """Return the first docstring paragraph of a class or dotted class path."""
    if isinstance(target, str):
        module_name, _, attr = target.rpartition(".")
        try:
            target = getattr(importlib.import_module(module_name), attr)
        except (ImportError, AttributeError):
            return ""
    return _first_para(getattr(target, "__doc__", ""))


def _gen_drivers_engines() -> str:
    from ovid2.config.engines import _KNOWN_TYPES
    from ovid2.connections.registry import CONNECTION_TYPE_MAP

    native = {"disc", "s3", "azure_blob", "snowflake", "access"}
    drows = []
    for name in sorted(CONNECTION_TYPE_MAP):
        drows.append(
            [
                f"`{name}`",
                _resolve_doc(CONNECTION_TYPE_MAP[name]),
                "native" if name in native else "legacy adapter (DuckDB only)",
            ]
        )
    from ovid2.core.engines.registry import ENGINE_TYPE_MAP

    erows = [
        [f"`{name}`", _resolve_doc(ENGINE_TYPE_MAP[name])]
        for name in sorted(_KNOWN_TYPES)
        if name in ENGINE_TYPE_MAP
    ]
    return "\n".join(
        [
            _front(
                "Drivers & engines",
                "Every storage driver (connection type) and compute engine Ovid2 ships.",
                ["user", "developer"],
            ),
            "A **driver** talks to a storage system; an **engine** runs the computation. "
            "They are orthogonal: any engine can read from any driver it has a staging "
            "strategy for. Concepts: [Connections & addresses](../02-concepts/storage.md), "
            "[Engines](../02-concepts/engines.md).\n",
            "## Drivers\n",
            _table(["Type", "Description", "Implementation"], drows),
            "## Engines\n",
            _table(["Type", "Description"], erows),
        ]
    )


def _gen_cdms() -> str:
    lines = [
        _front(
            "CDMs & vocabularies",
            "Every bundled common data model (tables, keys) and clinical vocabulary.",
            ["researcher", "developer"],
        ),
        "CDMs are YAML trees under `src/ovid2/resources/cdms/<cdm>/`; vocabularies live under "
        "`src/ovid2/resources/semantic/`. Narrative: [Data models](../05-data/index.md).\n",
    ]
    cdm_root = _RES / "cdms"
    summary = []
    details = []
    for cdm_dir in sorted(p for p in cdm_root.iterdir() if (p / "cdm.yaml").is_file()):
        cdm = yaml.safe_load((cdm_dir / "cdm.yaml").read_text(encoding="utf-8")) or {}
        name = cdm.get("name", cdm_dir.name)
        tables = list(cdm.get("tables") or [])
        origin = (cdm.get("source") or {}).get("origin", "")
        valuesets = (
            len(list((cdm_dir / "valuesets").glob("*.yaml")))
            if (cdm_dir / "valuesets").is_dir()
            else 0
        )
        summary.append(
            [f"[`{name}`](#{name})", cdm.get("version", ""), origin, len(tables), valuesets]
        )
        rows = []
        for t in tables:
            tpath = cdm_dir / "tables" / f"{t}.yaml"
            tdata = yaml.safe_load(tpath.read_text(encoding="utf-8")) if tpath.is_file() else {}
            tdata = tdata or {}
            key = ", ".join(f"`{k}`" for k in (tdata.get("composite_key") or []))
            nfields = len(tdata.get("fields") or [])
            rows.append([f"`{t}`", key, nfields, tdata.get("domain_description", "")])
        details.append(f"## {name}\n")
        details.append(
            f"Version **{cdm.get('version', '?')}** · {len(tables)} tables · "
            f"{valuesets} bounded valuesets.\n"
        )
        details.append(_table(["Table", "Composite key", "Fields", "Description"], rows))
    lines.append(_table(["CDM", "Version", "Origin", "Tables", "Valuesets"], summary))
    lines.extend(details)

    vocab_rows = []
    for vpath in sorted((_RES / "semantic" / "vocabularies").glob("*.yaml")):
        v = yaml.safe_load(vpath.read_text(encoding="utf-8")) or {}
        vocab_rows.append(
            [
                f"`{v.get('name', vpath.stem)}`",
                v.get("version", ""),
                _first_para(v.get("description")),
            ]
        )
    lines.append("## Clinical vocabularies\n")
    lines.append(
        "Bounded CDM valuesets are also registered automatically as vocabularies named "
        "`<cdm>.<table>.<column>`.\n"
    )
    lines.append(_table(["Vocabulary", "Version", "Description"], vocab_rows))
    return "\n".join(lines)


#: page slug → generator. Order = reading order inside the chapter (after index).
GENERATORS: dict[str, Callable[[], str]] = {
    "cli": _gen_cli,
    "api": _gen_api,
    "mcp-tools": _gen_mcp,
    "run-kinds": _gen_run_kinds,
    "transforms": _gen_transforms,
    "mapper-ops": _gen_mapper_ops,
    "adapters": _gen_adapters,
    "fixers": _gen_fixers,
    "drivers-engines": _gen_drivers_engines,
    "cdms": _gen_cdms,
}


def generate_reference() -> dict[str, str]:
    """Return ``{relative_path: markdown}`` for every generated page."""
    out: dict[str, str] = {}
    for slug, fn in GENERATORS.items():
        text = fn().rstrip() + "\n"
        while "\n\n\n" in text:
            text = text.replace("\n\n\n", "\n\n")
        out[f"{REFERENCE_CHAPTER}/{slug}.md"] = text
    return out


def write_reference(root: Path | None = None, *, check: bool = False) -> list[str]:
    """Write (or, with ``check``, compare) the generated reference pages.

    Args:
        root: Manual root (defaults to the packaged one).
        check: When ``True`` write nothing and return the stale paths.

    Returns:
        Relative paths written (or, with ``check``, the ones out of date).
    """
    root = root or manual_root()
    changed: list[str] = []
    for rel, text in generate_reference().items():
        target = root / rel
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if current == text:
            continue
        changed.append(rel)
        if not check:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
    return changed
