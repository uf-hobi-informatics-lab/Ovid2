def _subparsers(parser: argparse.ArgumentParser) -> argparse._SubParsersAction[Any] | None:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return action
    return None


def _help_map(sp: argparse._SubParsersAction[Any]) -> dict[str, str]:
    return {a.dest: a.help or "" for a in sp._choices_actions}


def _options_table(parser: argparse.ArgumentParser) -> str:
    rows = []
    for action in parser._actions:
        if isinstance(action, argparse._HelpAction | argparse._SubParsersAction):
            continue
        if action.help == argparse.SUPPRESS:
            continue
        if action.option_strings:
            flag = ", ".join(f"`{o}`" for o in action.option_strings)
            if action.nargs != 0 and action.metavar is not None:
                flag += f" `{action.metavar}`"
            elif action.nargs != 0 and not isinstance(
                action,
                argparse._StoreTrueAction | argparse._StoreFalseAction | argparse._CountAction,
            ):
                flag += f" `{action.dest.upper()}`"
        else:
            flag = f"`{action.metavar or action.dest}`"
        default = ""
        if (
            action.option_strings
            and action.default not in (None, False, argparse.SUPPRESS)
            and not isinstance(action, argparse._CountAction)
        ):
            default = f"`{action.default}`"
        choices = ", ".join(f"`{c}`" for c in action.choices) if action.choices else ""
        rows.append([flag, action.help or "", choices, default])
    if not rows:
        return ""
    return _table(["Argument", "Description", "Choices", "Default"], rows)


def _cli_section(
    name: str, parser: argparse.ArgumentParser, help_text: str, level: int, lines: list[str]
) -> None:
    hashes = "#" * level
    lines.append(f"{hashes} `{name}`\n")
    desc = _first_para(parser.description) or help_text
    if desc:
        lines.append(desc + "\n")
    opts = _options_table(parser)
    if opts:
        lines.append(opts)
    sp = _subparsers(parser)
    if sp is None:
        return
    helps = _help_map(sp)
    seen: set[int] = set()
    children = []
    for child_name, child in sp.choices.items():
        if id(child) in seen or child_name not in helps:
            continue  # aliases share a parser object / hidden aliases have no help entry
        seen.add(id(child))
        children.append((child_name, child))
    if level >= 4:
        lines.append(
            _table(
                ["Subcommand", "Description"], ([f"`{n}`", helps.get(n, "")] for n, _ in children)
            )
        )
        return
    for child_name, child in children:
        _cli_section(f"{name} {child_name}", child, helps.get(child_name, ""), level + 1, lines)


#: Pipeline packages the public reference may name (site packages stay out,
#: and the output must not depend on which packages a host has installed).
_PUBLIC_PIPELINES = frozenset({"example_pcornet", "pcornet_to_omop"})


def _gen_cli() -> str:
    from unittest import mock

    import ovid2.tools.templates as templates_mod
    from ovid2.cli.__main__ import _SUBCOMMANDS, _build_parser

    with mock.patch.object(
        templates_mod,
        "_source_installed",
        lambda template: template.source_pipeline in _PUBLIC_PIPELINES,
    ):
        parser = _build_parser()
    sp = _subparsers(parser)
    assert sp is not None
    helps = _help_map(sp)
    lines = [
        _front(
            "CLI reference",
            "Every `ovid2` command, subcommand and flag, generated from the real argument parser.",
            ["user", "developer"],
        ),
        "Global flags: `--version` prints the installed version; `-v` / `--verbose` "
        "raises log verbosity (repeat for more). Run any command with `--help` for "
        "the same information in your terminal.\n",
        "## Command index\n",
        _table(
            ["Command", "Purpose"],
            ([f"[`ovid2 {n}`](#ovid2-{n.replace('_', '_')})", h] for n, h, _ in _SUBCOMMANDS),
        ),
    ]
    for name, help_text, _module in _SUBCOMMANDS:
        child = sp.choices.get(name)
        if child is None:
            continue
        _cli_section(f"ovid2 {name}", child, helps.get(name, help_text), 2, lines)
    return "\n".join(lines)


