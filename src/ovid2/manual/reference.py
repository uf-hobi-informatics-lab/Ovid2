"""Generate the manual's *Reference* chapter from the live registries.

Every page written here carries ``generated: true`` front-matter and must
never be hand-edited — run ``ovid2 manual gen-reference`` instead. The
contract test ``tests/contract/test_manual_reference_fresh.py`` fails when
a committed page drifts from what this module produces, so the reference
can never silently fall behind the code.

Sources (all imported lazily inside :func:`generate_reference` — this
module is an *executor/dev-tool* surface, never imported by the web tier):

- CLI           → the real argparse tree from :mod:`ovid2.cli.__main__`.
- REST API      → ``tests/contract/data/openapi.snapshot.json`` when
                  present, else ``create_app().openapi()``.
- MCP tools     → ``ovid2.mcp.tools.*`` (``TOOL_NAME`` / description / args).
- Run kinds     → :data:`ovid2.run_kinds.KIND_REGISTRY`.
- Transforms    → :data:`ovid2.config.transforms_catalogue.TRANSFORM_CATALOGUE`.
- Mapper ops, formatter adapters, fixers → their registries (docstrings).
- Drivers, engines → :mod:`ovid2.connections.registry`, :mod:`ovid2.config.engines`.
- CDMs, vocabularies → the YAML trees under ``resources/``.

Output is deterministic (sorted, no timestamps) so regeneration is a no-op
when nothing changed.
"""

from __future__ import annotations

