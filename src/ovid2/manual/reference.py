_RES = Path(__file__).resolve().parent.parent / "resources"


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------


def _front(title: str, summary: str, audience: Iterable[str]) -> str:
    meta = {
        "title": title,
        "summary": summary,
        "audience": list(audience),
        "generated": True,
    }
    return (
        "---\n"
        + yaml.safe_dump(meta, sort_keys=False, allow_unicode=True, width=1000)
        + "---\n\n"
        + "<!-- Generated by `ovid2 manual gen-reference`. Do not edit by hand. -->\n\n"
    )


def _cell(text: Any) -> str:
    """Escape a value for a Markdown table cell."""
    s = " ".join(str(text if text is not None else "").split())
    return s.replace("|", "\\|")


_RST_ROLE_RE = re.compile(r":(?:class|func|meth|mod|data|attr|obj|exc|ref):`~?([^`]+)`")
_RST_LITERAL_RE = re.compile(r"``([^`]+)``")


def _clean_rst(text: str) -> str:
    """Turn reST roles / double-backtick literals into Markdown code spans."""
    text = _RST_ROLE_RE.sub(lambda m: f"`{m.group(1).rsplit('.', 1)[-1]}`", text)
    return _RST_LITERAL_RE.sub(r"`\1`", text)


def _first_para(doc: str | None) -> str:
    """Return the first paragraph of a docstring, joined into one line."""
    if not doc:
        return ""
    para = inspect.cleandoc(doc).split("\n\n", 1)[0]
    return _clean_rst(" ".join(para.split()))


def _table(headers: list[str], rows: Iterable[Iterable[Any]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(" --- " for _ in headers) + "|"]
    for row in rows:
        out.append("| " + " | ".join(_cell(c) for c in row) + " |")
    return "\n".join(out) + "\n"


def _code(value: str) -> str:
    return f"`{value}`" if value else ""


