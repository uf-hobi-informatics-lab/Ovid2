def _openapi() -> dict[str, Any]:
    snap = _REPO_ROOT / "tests" / "contract" / "data" / "openapi.snapshot.json"
    if snap.is_file():
        data: dict[str, Any] = json.loads(snap.read_text(encoding="utf-8"))
        return data
    from ovid2.web.app import create_app

    return create_app().openapi()


def _gen_api() -> str:
    spec = _openapi()
    groups: dict[str, list[tuple[str, str, str]]] = {}
    for path, ops in sorted(spec.get("paths", {}).items()):
        if not path.startswith("/api/v1/"):
            continue
        group = path.split("/")[3].split(":")[0]
        for method in ("get", "post", "put", "patch", "delete"):
            if method in ops:
                groups.setdefault(group, []).append(
                    (method.upper(), path, ops[method].get("summary", ""))
                )
    total = sum(len(v) for v in groups.values())
    lines = [
        _front(
            "REST API reference",
            "Every `/api/v1` endpoint grouped by resource, generated from the OpenAPI schema.",
            ["developer"],
        ),
        f"The control panel exposes **{total} operations** under `/api/v1`. The live, "
        "interactive schema is always available at `/docs` (Swagger UI), `/redoc`, and "
        "`/openapi.json` on a running server. Authentication, roles and the service-token "
        "flow are described in [Authentication & roles](../08-operations/auth.md).\n",
        "## Resources\n",
        _table(
            ["Resource", "Operations"],
            ([f"[`/{g}`](#{g})", len(ops)] for g, ops in sorted(groups.items())),
        ),
    ]
    for group, ops in sorted(groups.items()):
        lines.append(f"## {group}\n")
        lines.append(_table(["Method", "Path", "Summary"], ([m, f"`{p}`", s] for m, p, s in ops)))
    return "\n".join(lines)


