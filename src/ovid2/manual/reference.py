def _gen_mcp() -> str:
    import ovid2.mcp.tools as tools_pkg

    rows = []
    for info in sorted(pkgutil.iter_modules(tools_pkg.__path__), key=lambda i: i.name):
        if info.name.startswith("_"):
            continue
        mod = importlib.import_module(f"{tools_pkg.__name__}.{info.name}")
        name = getattr(mod, "TOOL_NAME", None)
        if not name:
            continue
        args_model = getattr(mod, "ARGS_MODEL", None)
        args = ""
        if args_model is not None and hasattr(args_model, "model_fields"):
            args = ", ".join(f"`{k}`" for k in args_model.model_fields)
        rows.append([f"`{name}`", getattr(mod, "TOOL_DESCRIPTION", ""), args])
    return "\n".join(
        [
            _front(
                "MCP tool reference",
                "Every tool Agent Ovid (the MCP server) exposes, with its arguments.",
                ["developer", "user"],
            ),
            f"`ovid2 mcp` exposes **{len(rows)} tools**. Each one is a thin, typed wrapper "
            "over a single `/api/v1` call — the agent tier never touches secrets, drivers or "
            "pipeline code. Destructive tools stop at a human approval gate. See "
            "[Agent Ovid (MCP)](../07-assistant/mcp.md) for set-up.\n",
            _table(["Tool", "Description", "Arguments"], rows),
        ]
    )


