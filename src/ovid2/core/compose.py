"""Dynamic docker-compose generation for Ovid2 instance isolation.

Produces a per-invocation docker-compose YAML with instance-scoped service
names, container names, and network name. Prevents conflicts when multiple
Ovid2 processes run concurrently on the same Docker host.

Volume mounts pull from :data:`ovid2.config.settings.DATA_DIR` and
:data:`LEGACY_CREDENTIALS_DIR` so the compose file adapts to XDG-style
developer layouts as well as the production ``/data``/``/ovid_credentials``
mounts.

Every service also runs as the invoking host uid/gid via ``user:`` +
an ``LD_PRELOAD=libnss_wrapper.so`` overlay so the container process
can read ``$XDG_CONFIG_HOME/ovid2/secrets.d/*.json`` (mode ``0o600``,
owned by the host user). See :func:`ovid2.core.docker.nss_wrapper_env`
for the pair of ``passwd`` / ``group`` overlay files the workers
consume; the files are generated by
:meth:`ovid2.core.isolation.OvidInstance.ensure_nss_files` before this
module writes the compose YAML.
"""

from __future__ import annotations

import logging
import os
from pathlib import Path
from typing import TYPE_CHECKING, Any

from ovid2.config.settings import DATA_DIR, DOCKER_IMAGE, LEGACY_CREDENTIALS_DIR
from ovid2.core.docker import (
    NSS_GROUP_IN_CONTAINER,
    NSS_PASSWD_IN_CONTAINER,
    NSS_WRAPPER_LIB,
    SPARK_CLASS_IN_CONTAINER,
    SPARK_LOGS_DIR_IN_CONTAINER,
    SPARK_WORK_DIR_IN_CONTAINER,
)
from ovid2.core.isolation import OvidInstance

if TYPE_CHECKING:
    from ovid2.tools.extra_mounts import ExtraMount

logger = logging.getLogger(__name__)

_PROJECT_ROOT: Path = Path(__file__).resolve().parents[3]  # repo root
DEFAULT_WORKER_CORES: int = 8
DEFAULT_WORKER_MEMORY: str = "56g"
DEFAULT_WORKER_MEMORY_LIMIT: str = "60g"
DEFAULT_MASTER_MEMORY_LIMIT: str = "8g"


def _volume_mounts(
    *,
    instance: OvidInstance,
    data_rw: bool = False,
    extra_mounts: list[ExtraMount] | None = None,
) -> list[str]:
    """Return the standard bind-mount list for master + workers.

    Args:
        instance: The per-invocation isolation context. Provides the
            host paths to the nss-wrapper ``passwd`` / ``group``
            overlay files that let the containers run as the host uid.
        data_rw: When ``True``, mount ``/data`` read-write. Reserved for
            ``ovid2 tools copy`` (kind=copy) whose destination address
            may legitimately live under ``/data``; every other command
            (etl / analysis / dq_checks) mounts read-only so the input
            drop cannot be mutated by a mis-authored transformation.
            See the adr-copy-job-kind design note.
        extra_mounts: Additional bind mounts appended after the
            standard set. Only supplied for copy jobs — the caller
            (``start_spark_cluster``) is responsible for confining
            these to that kind. Each mount is validated by
            :func:`ovid2.tools.extra_mounts.parse_extra_mount` before
            it reaches this layer.
    """
    data_mode = "rw" if data_rw else "ro"
    mounts = [
        f"{_PROJECT_ROOT}:/app",
        f"{DATA_DIR}:/data:{data_mode}",
    ]
    # Bind-mount the host user's XDG config tree so master and workers
    # see the same address configs, secrets, connections, and engine
    # specs as the driver container. Kept read-only — the pipeline
    # never mutates its own config files.
    host_xdg_config = Path(os.environ.get("XDG_CONFIG_HOME") or (Path.home() / ".config"))
    if host_xdg_config.is_dir():
        mounts.append(f"{host_xdg_config}:/ovid2-user-config:ro")
    # ``LEGACY_CREDENTIALS_DIR`` defaults to ``/ovid_credentials`` which
    # only exists on production hosts inherited from the pre-Ovid2
    # deployment. Guard the mount so hosts without that directory still
    # produce a valid compose file (docker refuses to bring services up
    # when a bind mount's source path does not exist).
    if Path(LEGACY_CREDENTIALS_DIR).is_dir():
        mounts.append(f"{LEGACY_CREDENTIALS_DIR}:/ovid_credentials:ro")
    # Legacy Ovid credential directory (Datavant + Snowflake key-pair
    # auth material) — mount read-only when present on the host so
    # workers can hit Snowflake if any RDD partition triggers a
    # connector call. Guarded by an ``is_dir`` check so hosts that
    # don't use the legacy convention still generate a valid compose
    # file.
    if Path("/usr/include/rsa").is_dir():
        mounts.append("/usr/include/rsa:/usr/include/rsa:ro")
    # nss-wrapper overlay so ``getpwuid`` resolves inside the container
    # when we run master + workers as the host uid. The files are
    # generated by :meth:`OvidInstance.ensure_nss_files`, which is
    # called from :func:`build_compose_dict` before this list is
    # materialised.
    mounts.append(f"{instance.nss_passwd_file}:{NSS_PASSWD_IN_CONTAINER}:ro")
    mounts.append(f"{instance.nss_group_file}:{NSS_GROUP_IN_CONTAINER}:ro")
    # Per-invocation Spark scratch dirs (``$SPARK_HOME/work`` and
    # ``$SPARK_HOME/logs``). With ``--user $UID:$GID`` overriding the
    # container process, an arbitrary host uid may not be able to write
    # to the baked-in dirs. The worker JVM then fails every executor
    # launch with ``IOException: Failed to create directory
    # $SPARK_HOME/work/app-<id>/<executor>/`` and the standalone
    # master flags the app FAILED after ``MAX_EXECUTOR_RETRIES`` (10)
    # failures, crashing the driver mid-``getOrCreate()`` with the
    # classic ``Master removed our application: FAILED`` +
    # ``getServletHandlers on a running MetricsSystem`` +
    # ``AppStatusListener NullPointerException`` cascade. Bind-mounting
    # a host-writable ``0777`` dir at each container path short-
    # circuits the failure regardless of what mode the baked-in dirs
    # carry, so this fix works on images that predate the corresponding
    # ``chmod`` line in ``docker/Dockerfile``.
    mounts.append(f"{instance.spark_work_dir}:{SPARK_WORK_DIR_IN_CONTAINER}:rw")
    mounts.append(f"{instance.spark_logs_dir}:{SPARK_LOGS_DIR_IN_CONTAINER}:rw")
    for m in extra_mounts or []:
        mounts.append(m.as_compose_volume())
    return mounts


def build_compose_dict(
    instance: OvidInstance,
    num_workers: int,
    *,
    data_rw: bool = False,
    extra_mounts: list[ExtraMount] | None = None,
) -> dict[str, Any]:
    """Construct the docker-compose dictionary for an instance.

    Args:
        instance: The isolation context that determines every name.
        num_workers: Number of worker services to include.
        data_rw: When ``True``, mount ``/data`` read-write across master
            and every worker. Reserved for the ``copy`` kind; every
            other kind keeps the ETL read-only contract.
        extra_mounts: Additional bind mounts (see :func:`_volume_mounts`).
            Applied uniformly across the master and every worker so
            no partition-to-node mapping can silently miss the mount.

    Returns:
        A dict suitable for ``yaml.safe_dump``.
    """
    master_service = instance.master_name
    network_service_key = "spark-network"

    compose: dict[str, Any] = {
        "version": "3.8",
        "services": {},
        "networks": {
            network_service_key: {
                "name": instance.network_name,
                "driver": "bridge",
            }
        },
    }

    # Generate the nss-wrapper overlay + Spark scratch dirs before we
    # build the volumes list — docker refuses to start a service when
    # a bind source is missing.
    instance.ensure_directories()
    instance.ensure_nss_files()
    volumes = _volume_mounts(
        instance=instance,
        data_rw=data_rw,
        extra_mounts=extra_mounts,
    )

    # Every service runs as the invoking host uid/gid so the read-only
    # XDG mount (``secrets.d/*.json``, mode ``0o600``) is readable, and
    # so any files the copy kind creates under ``/data`` land owned by
    # the operator instead of the image's baked-in ``ovid2`` (uid
    # 1001). See :func:`ovid2.core.docker.nss_wrapper_env` and
    # :meth:`OvidInstance.ensure_nss_files` for the passwd overlay
    # that keeps Java's ``user.home`` resolvable under the override.
    host_uid = os.getuid()
    host_gid = os.getgid()
    user_str = f"{host_uid}:{host_gid}"
    nss_env = [
        f"LD_PRELOAD={NSS_WRAPPER_LIB}",
        f"NSS_WRAPPER_PASSWD={NSS_PASSWD_IN_CONTAINER}",
        f"NSS_WRAPPER_GROUP={NSS_GROUP_IN_CONTAINER}",
    ]

    compose["services"][master_service] = {
        "image": DOCKER_IMAGE,
        "container_name": instance.master_name,
        "hostname": instance.master_name,
        "user": user_str,
        # Publish the master's web UI (8080) and RPC (7077) ports to
        # *ephemeral* host ports (the single-value ``"<container>"`` form
        # lets Docker pick a free host port) rather than fixed host ports.
        # Fixed host bindings (``"8080:8080"`` etc.) broke per-invocation
        # isolation: a second ovid2 cluster — or a leaked/cancelled one
        # still holding the port — collided with
        # ``Bind for 0.0.0.0:<port> failed: port is already allocated``.
        # The driver reaches the master over the shared docker network by
        # container name (``spark://<master>:7077``) and the readiness
        # probe runs *inside* the container via ``docker exec``, so no
        # host-side consumer depends on a stable port number; these
        # publishes exist only for optional UI browsing (find the mapped
        # port with ``docker port <master> 8080``). The application/driver
        # UI (4040) lives on the *driver* container, not the master, so it
        # is intentionally not published here.
        "ports": [
            "8080",
            "7077",
        ],
        # Host / ports are passed as ``Master`` CLI flags below; the
        # ``SPARK_MODE`` / ``SPARK_MASTER_*`` env vars only ever drove the
        # Bitnami entrypoint script, which upstream Spark does not have.
        "environment": [
            *nss_env,
        ],
        "volumes": volumes,
        # Override the image's ``ovid2`` entrypoint so ``command`` is executed
        # as a plain shell invocation (otherwise the master would attempt to
        # run ``ovid2 bash -c "..."`` and argparse would fail with exit 2).
        #
        # ``sbin/start-master.sh`` daemonises Java through ``spark-daemon.sh``
        # and returns immediately, which would exit PID 1 the moment the shell
        # short-circuits — Docker would then treat the master as ``Exited (0)``
        # and workers would report ``dependency failed to start``. Run the
        # master class directly in the foreground so the JVM *is* PID 1's
        # child and its lifetime governs the container's.
        #
        # ``command`` must be a single-element list here: docker-compose
        # forwards each list element as its own argv token, so a plain
        # string would be tokenised on whitespace and ``bash -c`` would
        # only receive the first word ("exec"), producing a silent exit 0.
        "entrypoint": ["/bin/bash", "-c"],
        "command": [
            f"exec {SPARK_CLASS_IN_CONTAINER} "
            "org.apache.spark.deploy.master.Master "
            f"--host {instance.master_name} --port 7077 --webui-port 8080"
        ],
        "networks": [network_service_key],
        "healthcheck": {
            "test": [
                "CMD",
                "bash",
                "-c",
                "wget -q -O - http://localhost:8080 | grep -q 'Spark Master'",
            ],
            "interval": "5s",
            "timeout": "10s",
            "retries": 20,
            "start_period": "10s",
        },
        "deploy": {"resources": {"limits": {"memory": DEFAULT_MASTER_MEMORY_LIMIT}}},
    }

    master_url = instance.spark_master_url()
    for i in range(1, num_workers + 1):
        worker_service = instance.worker_name(i)
        compose["services"][worker_service] = {
            "image": DOCKER_IMAGE,
            "container_name": worker_service,
            "user": user_str,
            "depends_on": {master_service: {"condition": "service_healthy"}},
            # Master URL / cores / memory go on the ``Worker`` command line
            # below (the Bitnami-only ``SPARK_MODE`` env is gone).
            "environment": [
                # Src-layout: the mounted repo is at ``/app`` but the
                # importable package lives at ``/app/src/ovid2``. Point
                # workers at both the source tree and the ``ovid2_pipelines``
                # PEP 420 namespace root so pickled closures shipped from
                # the driver deserialise against the same code.
                "PYTHONPATH=/app/src:/app/pipelines",
                "PYSPARK_PYTHON=python3",
                *nss_env,
            ],
            "volumes": volumes,
            # See the master service comment: override the image entrypoint
            # so ``command`` runs as an ordinary shell invocation, and run
            # the Worker class in the foreground so its JVM anchors PID 1.
            # ``command`` MUST be a single-element list — see the master
            # service comment for why.
            "entrypoint": ["/bin/bash", "-c"],
            "command": [
                f"exec {SPARK_CLASS_IN_CONTAINER} "
                f"org.apache.spark.deploy.worker.Worker {master_url} "
                f"--cores {DEFAULT_WORKER_CORES} --memory {DEFAULT_WORKER_MEMORY}"
            ],
            "networks": [network_service_key],
            "deploy": {"resources": {"limits": {"memory": DEFAULT_WORKER_MEMORY_LIMIT}}},
        }

    return compose


def generate_compose_file(
    instance: OvidInstance,
    num_workers: int,
    *,
    data_rw: bool = False,
    extra_mounts: list[ExtraMount] | None = None,
) -> Path:
    """Write the compose YAML to :attr:`OvidInstance.compose_file`.

    ``pyyaml`` is imported lazily so this module stays importable on hosts
    that don't have PyYAML installed (e.g. minimal CI images).

    Args:
        instance: Isolation context.
        num_workers: Number of worker services.
        data_rw: Forwarded to :func:`build_compose_dict`. Set by the
            copy-kind dispatch path so its destination address can
            write under ``/data``.
        extra_mounts: Additional bind mounts (copy-kind only).

    Returns:
        The path to the generated compose file.
    """
    import yaml  # deferred import

    instance.ensure_directories()
    compose = build_compose_dict(
        instance,
        num_workers,
        data_rw=data_rw,
        extra_mounts=extra_mounts,
    )
    with instance.compose_file.open("w", encoding="utf-8") as fh:
        yaml.safe_dump(compose, fh, sort_keys=False)
    logger.debug(
        "Generated compose file %s with %d workers for instance %s",
        instance.compose_file,
        num_workers,
        instance.instance_id,
    )
    return instance.compose_file
