"""The portable operation set every Ovid2 compute engine must implement.

Ovid2's rule (``adr-engine-universality.md``): **every engine runs every
pipeline, transform, formatter, fixer, mapper and check on every storage
type.** That works because shared and generated code is written against a
single, PySpark-shaped surface, and each engine implements all of it:

* :data:`FUNCTIONS` — column functions (``ovid2.core.engines.dsl``),
  including ``udf`` / ``pandas_udf``;
* :data:`DATAFRAME_METHODS`, :data:`COLUMN_METHODS`,
  :data:`GROUPED_METHODS`, :data:`WINDOW_METHODS`,
  :data:`SESSION_METHODS`, :data:`READER_METHODS` — the object API.

The lists are the union of what Ovid2 code actually calls (shared
transformations, mappers, formatters, transforms, the legacy runtime,
every pipeline package and the vendored legacy fix scripts — rescanned by
``tests/contract/test_engine_surface_complete.py``) and the commonly used
Spark API. A new call site that uses a name outside these lists fails
that contract test until the name is added here **and** implemented by
every engine.

:data:`SPARK_FUNCTION_NAMES` is the full ``pyspark.sql.functions`` name
list (for ``from pyspark.sql.functions import *`` in vendored legacy
code); names beyond :data:`FUNCTIONS` dispatch to the active engine and
are implemented on demand.

Tier-neutral: pure data, no engine imports.
"""

