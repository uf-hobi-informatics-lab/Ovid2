"""Word (DOCX) export — editable document with chart images (python-docx)."""

from __future__ import annotations

import io
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from ovid2.reports.render._common import chart_png, md_blocks, status_color

__all__ = ["write_docx"]


def _rgb(hex_: str) -> Any:
    from docx.shared import RGBColor

    h = hex_.lstrip("#")
    return RGBColor(int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))


def _first_font(css: str) -> str:
    return css.split(",")[0].strip().strip("'\"") or "Calibri"


def write_docx(model: Mapping[str, Any], path: Path) -> Path:
    """Write the render model as a Word document."""
    from docx import Document
    from docx.enum.section import WD_ORIENT
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Inches, Pt

    theme = model["theme"]
    c = theme["colors"]
    sizes = theme["sizes"]
    doc: Any = Document()
    normal = doc.styles["Normal"]
    normal.font.name = _first_font(theme["fonts"].get("body", ""))
    normal.font.size = Pt(int(sizes.get("base", 11)))
    normal.font.color.rgb = _rgb(c["text"])
    for name in ("Title", "Heading 1", "Heading 2"):
        style = doc.styles[name]
        style.font.name = _first_font(theme["fonts"].get("heading", ""))
        style.font.color.rgb = _rgb(c["text"])
    section = doc.sections[0]
    page = model.get("page") or {}
    if page.get("size") == "a4":
        section.page_width, section.page_height = Inches(8.27), Inches(11.69)
    elif page.get("size") == "legal":
        section.page_width, section.page_height = Inches(8.5), Inches(14)
    if page.get("orientation") == "landscape":
        section.orientation = WD_ORIENT.LANDSCAPE
        section.page_width, section.page_height = section.page_height, section.page_width
    for side in ("left_margin", "right_margin", "top_margin", "bottom_margin"):
        setattr(section, side, Inches(0.7))
    body_w = (
        int(section.page_width or 0)
        - int(section.left_margin or 0)
        - int(section.right_margin or 0)
    )
    footer = section.footer.paragraphs[0]
    footer.text = f"{model['title']} — generated by Ovid2 Report Studio"
    footer.runs[0].font.size = Pt(8)
    footer.runs[0].font.color.rgb = _rgb(c["muted"])

    def shade(cell: Any, hex_: str) -> None:
        tc_pr = cell._tc.get_or_add_tcPr()
        shd = OxmlElement("w:shd")
        shd.set(qn("w:val"), "clear")
        shd.set(qn("w:color"), "auto")
        shd.set(qn("w:fill"), hex_.lstrip("#"))
        tc_pr.append(shd)

    def md(text: str) -> None:
        for b in md_blocks(text):
            if b.kind.startswith("h"):
                para = doc.add_heading(level=2)
            elif b.kind == "li":
                para = doc.add_paragraph(style="List Bullet")
            else:
                para = doc.add_paragraph()
            for r in b.runs:
                if b.kind == "li" and r.text in ("• ",):
                    continue
                run = para.add_run(r.text)
                run.bold = r.bold
                run.italic = r.italic
                if r.code:
                    run.font.name = "Courier New"

    def muted(text: str) -> None:
        para = doc.add_paragraph()
        run = para.add_run(text)
        run.italic = True
        run.font.size = Pt(int(sizes.get("base", 11)) - 2)
        run.font.color.rgb = _rgb(c["muted"])

    doc.add_heading(model["title"], level=0)
    if model.get("subtitle"):
        muted(model["subtitle"])
    md(model.get("description") or "")
    for s in model["sections"]:
        if s.get("page_break_before"):
            doc.add_page_break()
        doc.add_heading(s["title"], level=1)
        md(s.get("description") or "")
        for b in s["blocks"]:
            r = b["renderer"]
            if b.get("title") and r != "kpi":
                doc.add_heading(b["title"], level=2)
            if r == "vega":
                png = chart_png(b["spec"], scale=2.0)
                frac = {"half": 0.5, "third": 0.4, "two_thirds": 0.7}.get(str(b.get("width")), 1.0)
                doc.add_picture(io.BytesIO(png), width=int(body_w * frac))
            elif r == "kpi":
                k = b["kpi"]
                para = doc.add_paragraph()
                run = para.add_run(k["display"])
                run.bold = True
                run.font.size = Pt(int(sizes.get("title", 20)) + 2)
                colour = {
                    "good": theme["status"].get("passed"),
                    "bad": theme["status"].get("exception"),
                }.get(str(k.get("status")))
                run.font.color.rgb = _rgb(colour or c["text"])
                lab = para.add_run("   " + k["label"])
                lab.font.color.rgb = _rgb(c["muted"])
            elif r == "table":
                t = b["table"]
                tbl = doc.add_table(rows=1, cols=len(t["columns"]))
                tbl.style = "Table Grid"
                for i, col in enumerate(t["columns"]):
                    cell = tbl.rows[0].cells[i]
                    cell.text = col["title"]
                    cell.paragraphs[0].runs[0].bold = True
                    shade(cell, c["surface"])
                idx = (
                    [col["name"] for col in t["columns"]].index(t["status_column"])
                    if t.get("status_column")
                    else None
                )
                for row in t["rows"]:
                    cells = tbl.add_row().cells
                    for i, v in enumerate(row):
                        cells[i].text = str(v)
                        if idx == i:
                            colour = status_color(theme, v)
                            if colour and cells[i].paragraphs[0].runs:
                                cells[i].paragraphs[0].runs[0].font.color.rgb = _rgb(colour)
                for row in tbl.rows:
                    for cell in row.cells:
                        for para in cell.paragraphs:
                            for run in para.runs:
                                run.font.size = Pt(int(sizes.get("base", 11)) - 2)
                if t.get("truncated"):
                    muted(f"Showing {len(t['rows'])} of {t['total_rows']} rows.")
            elif r in ("text", "callout"):
                md(b.get("markdown") or "")
            else:
                muted(str(b.get("error") or "unavailable"))
            if b.get("caption"):
                muted(b["caption"])
            if b.get("suppressed_cells"):
                muted(f"{b['suppressed_cells']} small cell(s) suppressed.")
    if model["options"].get("show_provenance", True):
        doc.add_heading("Provenance", level=2)
        for k, v in model["provenance"].items():
            if v in (None, ""):
                continue
            para = doc.add_paragraph()
            key = para.add_run(f"{str(k).replace('_', ' ')}: ")
            key.bold = True
            para.add_run(str(v))
            for run in para.runs:
                run.font.size = Pt(8)
    doc.core_properties.title = model["title"]
    doc.core_properties.author = "Ovid2 Report Studio"
    doc.save(str(path))
    return path


