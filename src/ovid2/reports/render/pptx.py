"""PowerPoint (PPTX) export — one 16:9 deck per report (python-pptx).

Layout of the deck:

* a **title slide** (title, subtitle, description);
* an optional **contents** slide when ``options.show_toc`` is set;
* per section, blocks are packed left-to-right into *rows* by their
  layout width (``full`` / ``two_thirds`` / ``half`` / ``third``) — the
  same packing the PDF writer uses — and **each row becomes one slide**
  headed by the section title. Tables always take a full row and are
  paginated across slides (``_TABLE_ROWS_PER_SLIDE`` rows each);
* an optional **provenance** slide (``options.show_provenance``).

Charts are rasterised with vl-convert (:func:`chart_png`) and fitted into
their cell, preserving aspect ratio. Slide backgrounds and type follow the
report theme, so ``presentation_dark`` yields a dark deck.
"""

from __future__ import annotations

import io
import struct
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from ovid2.reports.render._common import chart_png, md_blocks, status_color

__all__ = ["write_pptx"]

#: Slide geometry (inches) — 16:9 widescreen.
_SLIDE_W = 13.333
_SLIDE_H = 7.5
_MARGIN = 0.5
_HEAD_H = 0.9
_FOOT_H = 0.35
_GAP = 0.25

#: Data rows per table slide before continuing on the next slide.
_TABLE_ROWS_PER_SLIDE = 12

_WIDTH_FRAC = {"full": 1.0, "half": 0.5, "third": 1 / 3, "two_thirds": 2 / 3}


def _rgb(hex_: str) -> Any:
    from pptx.dml.color import RGBColor

    ctor: Any = RGBColor
    h = (hex_ or "#000000").lstrip("#")
    if len(h) == 3:
        h = "".join(ch * 2 for ch in h)
    return ctor(int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16))


def _first_font(css: str) -> str:
    return css.split(",")[0].strip().strip("'\"") or "Calibri"


def _png_size(data: bytes) -> tuple[int, int]:
    """Return ``(width, height)`` of a PNG from its IHDR chunk."""
    if data[:8] != b"\x89PNG\r\n\x1a\n" or len(data) < 24:
        return (4, 3)
    w, h = struct.unpack(">II", data[16:24])
    return (int(w) or 4, int(h) or 3)


#: Vega-Lite pixels per inch (CSS px) and the room left for axes / legends.
_PX_PER_IN = 96
_CHART_PAD_PX = 90


def fit_spec(spec: Mapping[str, Any], w_in: float, h_in: float) -> dict[str, Any]:
    """Return ``spec`` resized to fill a ``w_in`` × ``h_in`` inch slide cell.

    Only a numeric top-level ``width`` / ``height`` is adjusted (composite
    specs are left alone). Height grows to use the cell but never beyond
    1.8× the builder's choice, so small charts do not balloon.
    """
    out = dict(spec)
    if isinstance(out.get("width"), int | float):
        out["width"] = max(int(w_in * _PX_PER_IN) - _CHART_PAD_PX, 120)
    if isinstance(out.get("height"), int | float):
        want = int(h_in * _PX_PER_IN) - _CHART_PAD_PX
        out["height"] = max(min(want, int(out["height"] * 1.8)), 40)
    return out


def pack_rows(blocks: Sequence[Mapping[str, Any]]) -> list[list[tuple[Mapping[str, Any], float]]]:
    """Pack blocks into rows of ``(block, width_fraction)`` summing to ≤ 1.

    Tables always occupy a full row of their own.
    """
    rows: list[list[tuple[Mapping[str, Any], float]]] = []
    row: list[tuple[Mapping[str, Any], float]] = []
    used = 0.0
    for b in blocks:
        frac = _WIDTH_FRAC.get(str(b.get("width")), 1.0)
        if b.get("renderer") == "table":
            frac = 1.0
        if row and used + frac > 1.001:
            rows.append(row)
            row, used = [], 0.0
        row.append((b, frac))
        used += frac
    if row:
        rows.append(row)
    return rows


def write_pptx(model: Mapping[str, Any], path: Path) -> Path:
    """Write the render model as a PowerPoint deck."""
    from pptx import Presentation
    from pptx.enum.text import MSO_ANCHOR, PP_ALIGN
    from pptx.util import Inches, Pt

    theme = model["theme"]
    c = theme["colors"]
    sizes = theme["sizes"]
    body_font = _first_font(theme["fonts"].get("body", ""))
    head_font = _first_font(theme["fonts"].get("heading", ""))
    base = int(sizes.get("base", 11))
    prs: Any = Presentation()
    prs.slide_width = Inches(_SLIDE_W)
    prs.slide_height = Inches(_SLIDE_H)
    blank = prs.slide_layouts[6]
    footer_text = f"{model['title']} — generated by Ovid2 Report Studio"
    content_w = _SLIDE_W - 2 * _MARGIN

    def new_slide() -> Any:
        slide = prs.slides.add_slide(blank)
        fill = slide.background.fill
        fill.solid()
        fill.fore_color.rgb = _rgb(c.get("background", "#ffffff"))
        return slide

    def style_run(
        run: Any,
        *,
        size: float,
        colour: str,
        bold: bool = False,
        italic: bool = False,
        font: str | None = None,
    ) -> None:
        run.font.size = Pt(size)
        run.font.bold = bold
        run.font.italic = italic
        run.font.name = font or body_font
        run.font.color.rgb = _rgb(colour)

    def textbox(slide: Any, x: float, y: float, w: float, h: float) -> Any:
        box = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
        tf = box.text_frame
        tf.word_wrap = True
        tf.margin_left = tf.margin_right = Inches(0.05)
        return tf

    def _add_run(para: Any, text: str) -> Any:
        run = para.add_run()
        run.text = text
        return run

    def put_text(
        tf: Any,
        text: str,
        *,
        size: float,
        colour: str,
        bold: bool = False,
        italic: bool = False,
        font: str | None = None,
        first: bool = True,
    ) -> Any:
        para = tf.paragraphs[0] if first and not tf.paragraphs[0].runs else tf.add_paragraph()
        style_run(
            _add_run(para, text), size=size, colour=colour, bold=bold, italic=italic, font=font
        )
        return para

    def md_into(tf: Any, text: str, size: float) -> None:
        for blk in md_blocks(text):
            para = tf.paragraphs[0] if not tf.paragraphs[0].runs else tf.add_paragraph()
            heading = blk.kind.startswith("h")
            for r in blk.runs:
                run = _add_run(para, r.text)
                style_run(
                    run,
                    size=size + (4 if heading else 0),
                    colour=c["text"],
                    bold=r.bold or heading,
                    italic=r.italic,
                    font="Courier New" if r.code else (head_font if heading else None),
                )
            if blk.kind == "li" and blk.level > 1:
                para.level = min(blk.level - 1, 4)
            para.space_after = Pt(4)

    def chrome(slide: Any, heading: str, sub: str = "") -> None:
        tf = textbox(slide, _MARGIN, 0.3, content_w, _HEAD_H - 0.2)
        tf.vertical_anchor = MSO_ANCHOR.MIDDLE
        put_text(
            tf,
            heading,
            size=int(sizes.get("heading", 16)) + 8,
            colour=c["text"],
            bold=True,
            font=head_font,
        )
        if sub:
            put_text(tf, sub, size=base, colour=c["muted"], first=False)
        bar = slide.shapes.add_shape(
            1, Inches(_MARGIN), Inches(0.3 + _HEAD_H - 0.12), Inches(1.2), Inches(0.05)
        )
        bar.fill.solid()
        bar.fill.fore_color.rgb = _rgb(c.get("accent", c["text"]))
        bar.line.fill.background()
        ft = textbox(slide, _MARGIN, _SLIDE_H - _FOOT_H - 0.1, content_w, _FOOT_H)
        put_text(ft, footer_text, size=9, colour=c["muted"])

    def note_lines(b: Mapping[str, Any]) -> list[str]:
        lines = []
        if b.get("caption"):
            lines.append(str(b["caption"]))
        if b.get("suppressed_cells"):
            lines.append(f"{b['suppressed_cells']} small cell(s) suppressed.")
        return lines

    def draw_block(
        slide: Any,
        b: Mapping[str, Any],
        x: float,
        y: float,
        w: float,
        h: float,
        rows: Sequence[Sequence[Any]] | None = None,
        note: str = "",
    ) -> None:
        r = b["renderer"]
        notes = note_lines(b) + ([note] if note else [])
        title_h = 0.4 if (b.get("title") and r != "kpi") else 0.0
        note_h = 0.3 * len(notes)
        if title_h:
            tf = textbox(slide, x, y, w, title_h)
            put_text(
                tf, str(b["title"]), size=base + 3, colour=c["text"], bold=True, font=head_font
            )
        by, bh = y + title_h, max(h - title_h - note_h, 0.5)
        if r == "vega":
            png = chart_png(fit_spec(b["spec"], w, bh), scale=2.0)
            pw, ph = _png_size(png)
            scale = min(w / pw, bh / ph)
            iw, ih = pw * scale, ph * scale
            slide.shapes.add_picture(
                io.BytesIO(png), Inches(x + (w - iw) / 2), Inches(by), Inches(iw), Inches(ih)
            )
        elif r == "kpi":
            k = b["kpi"]
            panel = slide.shapes.add_shape(
                1, Inches(x), Inches(by), Inches(w), Inches(min(bh, 2.2))
            )
            panel.fill.solid()
            panel.fill.fore_color.rgb = _rgb(c.get("surface", c.get("background", "#ffffff")))
            panel.line.color.rgb = _rgb(c.get("border", c["muted"]))
            tf = panel.text_frame
            tf.word_wrap = True
            tf.vertical_anchor = MSO_ANCHOR.MIDDLE
            colour = {
                "good": theme["status"].get("passed"),
                "bad": theme["status"].get("exception"),
            }.get(str(k.get("status"))) or c["text"]
            p = put_text(
                tf,
                str(k["display"]),
                size=int(sizes.get("title", 20)) + 12,
                colour=colour,
                bold=True,
                font=head_font,
            )
            p.alignment = PP_ALIGN.CENTER
            p2 = put_text(tf, str(k["label"]), size=base + 1, colour=c["muted"], first=False)
            p2.alignment = PP_ALIGN.CENTER
        elif r == "table":
            t = b["table"]
            cols = t["columns"]
            data = list(rows if rows is not None else t["rows"])
            shape = slide.shapes.add_table(
                len(data) + 1,
                max(len(cols), 1),
                Inches(x),
                Inches(by),
                Inches(w),
                Inches(min(bh, 0.32 * (len(data) + 1))),
            )
            tbl = shape.table
            idx = (
                [col["name"] for col in cols].index(t["status_column"])
                if t.get("status_column") in [col["name"] for col in cols]
                else None
            )
            cell_size = max(base - 2, 8)

            def set_cell(
                cell: Any, text: str, *, fill: str, colour: str, bold: bool = False
            ) -> None:
                cell.fill.solid()
                cell.fill.fore_color.rgb = _rgb(fill)
                cell.text = ""
                run = _add_run(cell.text_frame.paragraphs[0], text)
                style_run(run, size=cell_size, colour=colour, bold=bold)
                cell.margin_top = cell.margin_bottom = Inches(0.03)

            surface = c.get("surface", c.get("background", "#ffffff"))
            bg = c.get("background", "#ffffff")
            for i, col in enumerate(cols):
                set_cell(
                    tbl.cell(0, i), str(col["title"]), fill=surface, colour=c["text"], bold=True
                )
            zebra = t.get("zebra", True)
            for ri, row in enumerate(data, start=1):
                fill = surface if (zebra and ri % 2 == 0) else bg
                for ci, v in enumerate(row[: len(cols)]):
                    colour = (status_color(theme, v) if idx == ci else None) or c["text"]
                    set_cell(
                        tbl.cell(ri, ci), "" if v is None else str(v), fill=fill, colour=colour
                    )
        elif r in ("text", "callout"):
            if r == "callout":
                edge = slide.shapes.add_shape(1, Inches(x), Inches(by), Inches(0.06), Inches(bh))
                edge.fill.solid()
                edge.fill.fore_color.rgb = _rgb(c.get("accent", c["text"]))
                edge.line.fill.background()
                x, w = x + 0.15, w - 0.15
            tf = textbox(slide, x, by, w, bh)
            md_into(tf, str(b.get("markdown") or ""), base + 2)
        else:
            tf = textbox(slide, x, by, w, bh)
            put_text(
                tf, str(b.get("error") or "unavailable"), size=base, colour=c["muted"], italic=True
            )
        if notes:
            tf = textbox(slide, x, y + h - note_h, w, note_h)
            for i, line in enumerate(notes):
                put_text(
                    tf, line, size=max(base - 2, 8), colour=c["muted"], italic=True, first=i == 0
                )

    # -- title slide -------------------------------------------------------
    slide = new_slide()
    tf = textbox(slide, 1.0, 2.2, _SLIDE_W - 2.0, 1.4)
    tf.vertical_anchor = MSO_ANCHOR.BOTTOM
    put_text(
        tf,
        str(model["title"]),
        size=int(sizes.get("title", 20)) + 16,
        colour=c["text"],
        bold=True,
        font=head_font,
    )
    bar = slide.shapes.add_shape(1, Inches(1.0), Inches(3.7), Inches(1.6), Inches(0.07))
    bar.fill.solid()
    bar.fill.fore_color.rgb = _rgb(c.get("accent", c["text"]))
    bar.line.fill.background()
    tf = textbox(slide, 1.0, 3.9, _SLIDE_W - 2.0, 2.6)
    if model.get("subtitle"):
        put_text(tf, str(model["subtitle"]), size=base + 6, colour=c["muted"])
    if model.get("description"):
        md_into(tf, str(model["description"]), base + 2)

    # -- contents ----------------------------------------------------------
    if model["options"].get("show_toc") and model["sections"]:
        slide = new_slide()
        chrome(slide, "Contents")
        tf = textbox(slide, _MARGIN, 0.3 + _HEAD_H + _GAP, content_w, 5.2)
        for i, s in enumerate(model["sections"], start=1):
            put_text(tf, f"{i}. {s['title']}", size=base + 6, colour=c["text"], first=i == 1)

    # -- sections ----------------------------------------------------------
    top = 0.3 + _HEAD_H + _GAP
    avail_h = _SLIDE_H - top - _FOOT_H - _GAP
    for s in model["sections"]:
        rows = pack_rows(s["blocks"])
        desc = str(s.get("description") or "")
        if not rows or desc:
            slide = new_slide()
            chrome(slide, str(s["title"]))
            if desc:
                tf = textbox(slide, _MARGIN, top, content_w, avail_h)
                md_into(tf, desc, base + 4)
        for row in rows:
            first, _frac = row[0]
            if len(row) == 1 and first["renderer"] == "table":
                t = first["table"]
                data = list(t["rows"])
                chunks = [
                    data[i : i + _TABLE_ROWS_PER_SLIDE]
                    for i in range(0, len(data), _TABLE_ROWS_PER_SLIDE)
                ] or [[]]
                for ci, chunk in enumerate(chunks):
                    slide = new_slide()
                    chrome(slide, str(s["title"]) + (" (cont.)" if ci else ""))
                    note = ""
                    if ci == len(chunks) - 1 and t.get("truncated"):
                        note = f"Showing {len(data)} of {t['total_rows']} rows."
                    draw_block(
                        slide, first, _MARGIN, top, content_w, avail_h, rows=chunk, note=note
                    )
                continue
            slide = new_slide()
            chrome(slide, str(s["title"]))
            x = _MARGIN
            gaps = _GAP * (len(row) - 1)
            for b, frac in row:
                w = (content_w - gaps) * frac / max(sum(f for _b, f in row), 1.0)
                draw_block(slide, b, x, top, w, avail_h)
                x += w + _GAP

    # -- provenance --------------------------------------------------------
    if model["options"].get("show_provenance", True):
        slide = new_slide()
        chrome(slide, "Provenance")
        tf = textbox(slide, _MARGIN, top, content_w, avail_h)
        first_line = True
        for k, v in model["provenance"].items():
            if v in (None, ""):
                continue
            para = tf.paragraphs[0] if first_line else tf.add_paragraph()
            first_line = False
            style_run(
                _add_run(para, f"{str(k).replace('_', ' ')}: "),
                size=base,
                colour=c["text"],
                bold=True,
            )
            style_run(_add_run(para, str(v)), size=base, colour=c["muted"])

    prs.core_properties.title = str(model["title"])
    prs.core_properties.author = "Ovid2 Report Studio"
    prs.save(str(path))
    return path


