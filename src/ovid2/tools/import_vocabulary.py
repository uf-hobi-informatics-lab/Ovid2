"""Import a cross-CDM vocabulary from the OMOP CONCEPT bundle (S3).

The OMOP standardised-vocabulary bundle ships one big ``CONCEPT.csv``
file (tab-delimited) that contains rows from every clinical vocabulary
OHDSI has curated — LOINC, SNOMED, ICD-10-CM, ICD-9-CM, RxNorm, NDC,
CVX, and 60+ others. Each row carries a ``vocabulary_id`` column that
identifies its source.

Ovid2's semantic layer wants each vocabulary as a first-class
:class:`~ovid2.semantic.handle.VocabularyHandle`. Loading the full
CONCEPT.csv on every pipeline start is wasteful when a pipeline only
touches LOINC codes, so this tool **slices** CONCEPT.csv by
``vocabulary_id`` into a small per-vocabulary CSV under
``$OVID2_MATERIAL_DIR/omop_cdm/v5.3/vocab_slices/<vocab>.csv``.

The generated slice CSVs preserve CONCEPT.csv's header and column
order verbatim. The accompanying vocabulary YAML file
(``src/ovid2/resources/semantic/vocabularies/<vocab>.yaml``) points at
the slice with a ``source_path`` leg and inherits the same
``code_column`` / ``description_column`` / ``domain_column`` as OMOP
CONCEPT.

Usage::

    ovid2 tools import-vocabulary \\
        --source /path/to/omop_cdm/ \\
        --vocab loinc snomed icd10cm icd9cm rxnorm ndc \\
        --slice-dir $OVID2_MATERIAL_DIR/omop_cdm/v5.3/vocab_slices/ \\
        --out-dir src/ovid2/resources/semantic/vocabularies/ \\
        [--write]

Dry-run by default (streams CONCEPT.csv once per vocab, reports row
counts, writes nothing). Pass ``--write`` to persist both the slice
CSVs and the vocabulary YAMLs atomically.

The tool is dev-only: not exposed on the REST API or MCP because
vocabulary imports are a rare, one-per-OMOP-release operation.
"""

from __future__ import annotations

import argparse
import csv
import logging
import os
import sys
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import TYPE_CHECKING, Any, TextIO

