def _spec_by_slug(slug: str) -> _VocabSpec | None:
    """Return the :class:`_VocabSpec` for ``slug``, or ``None``."""
    for spec in _KNOWN_VOCABS:
        if spec.slug == slug:
            return spec
    return None


# ---------------------------------------------------------------------------
# CONCEPT.csv reader
# ---------------------------------------------------------------------------


def _open_concept_csv(source_dir: Path) -> Path:
    """Return the path to CONCEPT.csv under ``source_dir``.

    The OMOP bundle uses uppercase filenames on the disk we've observed;
    accept common variants defensively.
    """
    for candidate in ("CONCEPT.csv", "Concept.csv", "concept.csv"):
        path = source_dir / candidate
        if path.is_file():
            return path
    raise FileNotFoundError(
        f"No CONCEPT.csv found under {source_dir}. "
        "Expected one of CONCEPT.csv / Concept.csv / concept.csv."
    )


def _read_vocabulary_versions(source_dir: Path) -> dict[str, str]:
    """Return ``{vocabulary_id: vocabulary_version}`` from VOCABULARY.csv.

    Missing VOCABULARY.csv returns an empty dict — the tool still runs,
    just without per-vocab version tags on the emitted YAML.
    """
    for candidate in ("VOCABULARY.csv", "Vocabulary.csv", "vocabulary.csv"):
        path = source_dir / candidate
        if path.is_file():
            break
    else:
        logger.warning(
            "No VOCABULARY.csv under %s; emitted YAML will omit per-vocab versions.",
            source_dir,
        )
        return {}

    result: dict[str, str] = {}
    with path.open(encoding="utf-8", newline="") as fh:
        reader = csv.reader(fh, delimiter="\t")
        header = next(reader, None)
        if header is None:
            return result
        # Column names may be lower- or upper-cased across OMOP releases;
        # be lenient.
        lower = [h.strip().lower() for h in header]
        try:
            id_idx = lower.index("vocabulary_id")
            ver_idx = lower.index("vocabulary_version")
        except ValueError:
            logger.warning(
                "%s: missing vocabulary_id/version columns; skipping version tags.",
                path,
            )
            return result
        for row in reader:
            if len(row) <= max(id_idx, ver_idx):
                continue
            vocab_id = (row[id_idx] or "").strip()
            version = (row[ver_idx] or "").strip()
            if vocab_id and version:
                result[vocab_id] = version
    return result


# ---------------------------------------------------------------------------
# Slice writer
# ---------------------------------------------------------------------------


def _slice_concept_csv(
    concept_path: Path,
    wanted_ids: set[str],
    outputs: dict[str, TextIO] | None,
) -> dict[str, int]:
    """Stream CONCEPT.csv once and count / (optionally) write rows per vocab.

    Args:
        concept_path: Filesystem path to CONCEPT.csv.
        wanted_ids: Set of ``vocabulary_id`` values to keep.
        outputs: When not ``None``, maps ``vocabulary_id`` → open,
            write-mode text file. Header is written to each file before
            the first data row lands.

    Returns:
        ``{vocabulary_id: row_count}`` (data rows only, header excluded).
    """
    counts: dict[str, int] = dict.fromkeys(wanted_ids, 0)
    with concept_path.open(encoding="utf-8", newline="") as fh:
        reader = csv.reader(fh, delimiter="\t")
        header = next(reader, None)
        if header is None:
            raise ValueError(f"{concept_path}: empty file (no header).")
        lower = [h.strip().lower() for h in header]
        try:
            vocab_idx = lower.index("vocabulary_id")
        except ValueError as exc:
            raise ValueError(f"{concept_path}: header missing 'vocabulary_id' column.") from exc

        writers: dict[str, _CsvWriter] = {}
        if outputs is not None:
            for vid, out_fh in outputs.items():
                w = csv.writer(out_fh, delimiter="\t", lineterminator="\n")
                w.writerow(header)
                writers[vid] = w

        for row in reader:
            if len(row) <= vocab_idx:
                continue
            vid = row[vocab_idx]
            if vid not in wanted_ids:
                continue
            counts[vid] += 1
            if outputs is not None:
                writers[vid].writerow(row)

    return counts


# ---------------------------------------------------------------------------
# YAML rendering
# ---------------------------------------------------------------------------


def _render_vocab_yaml(spec: _VocabSpec, version: str) -> dict[str, Any]:
    """Render a vocabulary YAML payload for ``spec``.

    The emitted document is a superset of what the S3 hand-authored
    YAMLs contain (`v`, `kind`, `name`, `version`, `description`,
    `view_name`, `code_column`, `description_column`, `domain_column`,
    `source_path`, `delimiter`, `header`, `required`, `tags`).
    """
    return {
        "v": 1,
        "kind": "vocabulary",
        "name": spec.slug,
        "version": version or "OMOP 5.3 slice",
        "description": spec.description,
        "view_name": spec.slug,
        "code_column": "concept_code",
        "description_column": "concept_name",
        "domain_column": "domain_id",
        "source_path": f"${{OMOP_CDM_DIR}}/vocab_slices/{spec.slug}.csv",
        "delimiter": "\t",
        "header": True,
        "required": False,
        "tags": list(spec.tags),
        "_generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
    }


def _dump_yaml(payload: dict[str, Any]) -> str:
    """Serialise ``payload`` to a stable, human-readable YAML string."""
    return yaml.safe_dump(
        payload,
        sort_keys=False,
        allow_unicode=True,
        width=100,
        default_flow_style=False,
    )


def _write_atomic(path: Path, text: str, *, mode: int = 0o644) -> None:
    """Write ``text`` to ``path`` atomically with ``mode``."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.chmod(tmp, mode)
    tmp.replace(path)


# ---------------------------------------------------------------------------
# CLI wiring
# ---------------------------------------------------------------------------


def register(subparsers: argparse._SubParsersAction[argparse.ArgumentParser]) -> None:
    """Register the ``tools import-vocabulary`` subcommand."""
    parser = subparsers.add_parser(
        "import-vocabulary",
        help="Slice a vocabulary out of the OMOP CONCEPT bundle (S3).",
        description=__doc__,
    )
    parser.add_argument(
        "--source",
        required=True,
        help=(
            "Directory containing CONCEPT.csv (and, optionally, "
            "VOCABULARY.csv). Typically the OMOP CDM v5.3 bundle."
        ),
    )
    parser.add_argument(
        "--vocab",
        nargs="+",
        required=True,
        choices=list(_KNOWN_SLUGS),
        metavar="VOCAB",
        help=("One or more vocabulary slugs to import. Choices: " + ", ".join(_KNOWN_SLUGS)),
    )
    parser.add_argument(
        "--slice-dir",
        required=True,
        help=(
            "Directory where the per-vocabulary slice CSVs will be "
            "written. Should match `${OMOP_CDM_DIR}/vocab_slices/` "
            "used by the emitted YAML's source_path."
        ),
    )
    parser.add_argument(
        "--out-dir",
        required=True,
        help=(
            "Directory where the per-vocabulary YAML files will be "
            "written. Typically src/ovid2/resources/semantic/vocabularies/."
        ),
    )
    parser.add_argument(
        "--write",
        action="store_true",
        help=(
            "Actually persist the slice CSVs and YAMLs (default: "
            "dry-run, prints per-vocab row counts and a sample YAML)."
        ),
    )
    parser.add_argument(
        "--allow-empty",
        action="store_true",
        help=(
            "Do not fail when a requested vocabulary matches zero rows. "
            "Default: exit non-zero so typos in `--vocab` surface loudly."
        ),
    )
    parser.set_defaults(_entry=main)


def main(args: argparse.Namespace) -> int:
    """Entry point for ``ovid2 tools import-vocabulary``."""
    source_dir = Path(args.source)
    if not source_dir.is_dir():
        print(
            f"[ovid2 tools import-vocabulary] source not a directory: {source_dir}",
            file=sys.stderr,
        )
        return 2
    try:
        concept_path = _open_concept_csv(source_dir)
    except FileNotFoundError as exc:
        print(f"[ovid2 tools import-vocabulary] {exc}", file=sys.stderr)
        return 2

    slice_dir = Path(args.slice_dir)
    out_dir = Path(args.out_dir)

    # Build the wanted-ids map: {vocab_id: _VocabSpec}.
    specs_by_id: dict[str, _VocabSpec] = {}
    for slug in args.vocab:
        spec = _spec_by_slug(slug)
        if spec is None:
            # argparse `choices=` should have caught this; defensive.
            print(
                f"[ovid2 tools import-vocabulary] unknown vocab: {slug}",
                file=sys.stderr,
            )
            return 2
        specs_by_id[spec.vocabulary_id] = spec
    wanted_ids = set(specs_by_id.keys())

    versions = _read_vocabulary_versions(source_dir)

    # First pass: stream CONCEPT.csv, count matches, hold open file handles
    # only when --write is set.
    outputs: dict[str, TextIO] | None = None
    open_handles: list[TextIO] = []
    if args.write:
        slice_dir.mkdir(parents=True, exist_ok=True)
        outputs = {}
        for vid, spec in specs_by_id.items():
            path = slice_dir / f"{spec.slug}.csv"
            # Write to a `.tmp` then atomically rename at the end.
            tmp = path.with_suffix(path.suffix + ".tmp")
            fh: TextIO = tmp.open("w", encoding="utf-8", newline="")
            outputs[vid] = fh
            open_handles.append(fh)

    try:
        counts = _slice_concept_csv(concept_path, wanted_ids, outputs)
    finally:
        for fh in open_handles:
            fh.close()

    # Print the report.
    print(f"[ovid2 tools import-vocabulary] source={concept_path}")
    for vid, spec in specs_by_id.items():
        version = versions.get(vid, "")
        version_note = f" (v={version})" if version else ""
        print(f"  {spec.slug:<12} vocabulary_id={vid:<10} rows={counts[vid]:>10d}{version_note}")

    # Loud empty-slice failure (unless --allow-empty).
    empty = [specs_by_id[vid].slug for vid, n in counts.items() if n == 0]
    if empty and not args.allow_empty:
        print(
            f"\n[ovid2 tools import-vocabulary] refusing to write empty slice(s): "
            f"{', '.join(empty)}. Pass --allow-empty to override.",
            file=sys.stderr,
        )
        if args.write:
            # Clean up the .tmp files we opened.
            for vid in specs_by_id:
                tmp = (slice_dir / f"{specs_by_id[vid].slug}.csv").with_suffix(".csv.tmp")
                if tmp.exists():
                    tmp.unlink()
        return 1

    if not args.write:
        # Dry-run — print a sample YAML for the first requested vocab.
        first = next(iter(specs_by_id.values()))
        sample = _render_vocab_yaml(first, versions.get(first.vocabulary_id, ""))
        print("\nDry-run — pass --write to persist. Sample vocabulary YAML:")
        print(_dump_yaml(sample))
        return 0

    # Second pass: atomically rename each .tmp slice into place, then
    # write the YAML for each vocab.
    out_dir.mkdir(parents=True, exist_ok=True)
    for vid, spec in specs_by_id.items():
        tmp = (slice_dir / f"{spec.slug}.csv").with_suffix(".csv.tmp")
        final = slice_dir / f"{spec.slug}.csv"
        os.chmod(tmp, 0o644)
        tmp.replace(final)
        print(f"[write] {final}  ({counts[vid]} row(s))")

        yaml_payload = _render_vocab_yaml(spec, versions.get(vid, ""))
        # Strip the private `_generated_at` marker from the persisted
        # YAML — it's useful in the dry-run report but noise on disk.
        yaml_payload.pop("_generated_at", None)
        yaml_path = out_dir / f"{spec.slug}.yaml"
        _write_atomic(yaml_path, _dump_yaml(yaml_payload))
        print(f"[write] {yaml_path}")

    return 0


if __name__ == "__main__":
    parser = argparse.ArgumentParser(prog="import-vocabulary")
    subs = parser.add_subparsers(dest="_command", metavar="COMMAND", required=True)
    register(subs)
    ns = parser.parse_args()
    sys.exit(main(ns))
